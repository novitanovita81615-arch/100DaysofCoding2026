public class Main {
    public static void main(String[] args) {
        
        // byte = kecil
        // short = agak besar
        // int = besar
        // long = sangat besar
        // note = Semakin besar kapasitasnya, semakin besar angka yang bisa disimpan.
        
        byte a = 127;
        short b = 32767;
        int c = 2147483647;
        long d = 18000000000000000L;

        System.out.println("byte : " + a);
        System.out.println("short : " + b);
        System.out.println("int : " + c);
        System.out.println("long : " + d);
    }
}